// Config plugin for the kiosk's USB slip printer (Android).
//
// Adds a USB_DEVICE_ATTACHED intent filter to the main activity, with a device filter that matches
// printer-class (7) devices. When a printer is plugged in, Android offers to open the kiosk and
// shows "Use by default for this USB device"; ticking it makes Android remember the permission,
// so the kiosk never has to ask in front of a patient.

const { AndroidConfig, withAndroidManifest, withDangerousMod } = require('expo/config-plugins');
const fs = require('fs');
const path = require('path');

const USB_ATTACHED = 'android.hardware.usb.action.USB_DEVICE_ATTACHED';
const FILTER_NAME = 'device_filter';
const FILTER_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by modules/medios-printer/app.plugin.js: USB printers (class 7). -->
<resources>
    <usb-device class="7" />
</resources>
`;

const named = (name) => (entry) => entry.$ && entry.$['android:name'] === name;

function withUsbAttachedIntent(config) {
  return withAndroidManifest(config, (config) => {
    const activity = AndroidConfig.Manifest.getMainActivityOrThrow(config.modResults);

    const filters = activity['intent-filter'] ?? [];
    if (!filters.some((filter) => (filter.action ?? []).some(named(USB_ATTACHED)))) {
      filters.push({ action: [{ $: { 'android:name': USB_ATTACHED } }] });
    }
    activity['intent-filter'] = filters;

    const meta = (activity['meta-data'] ?? []).filter((entry) => !named(USB_ATTACHED)(entry));
    meta.push({ $: { 'android:name': USB_ATTACHED, 'android:resource': `@xml/${FILTER_NAME}` } });
    activity['meta-data'] = meta;

    return config;
  });
}

function withDeviceFilterResource(config) {
  return withDangerousMod(config, [
    'android',
    async (config) => {
      const dir = path.join(config.modRequest.platformProjectRoot, 'app', 'src', 'main', 'res', 'xml');
      await fs.promises.mkdir(dir, { recursive: true });
      await fs.promises.writeFile(path.join(dir, `${FILTER_NAME}.xml`), FILTER_XML);
      return config;
    },
  ]);
}

module.exports = function withMediosPrinter(config) {
  return withDeviceFilterResource(withUsbAttachedIntent(config));
};
